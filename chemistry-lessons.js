function factsTT(name,icon,qs){
  return {
    icon:icon,name:name,
    generate:()=>{const q=qs[randInt(0,qs.length-1)];return{q}},
    template:(q)=>({text:q.q,answer:q.a,hint:q.h,solution:`Ответ: <b>${Array.isArray(q.a)?q.a[0]:q.a}</b>.`})
  };
}

